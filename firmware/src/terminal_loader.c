/*
 * Helper-0 loader for the V92 terminal overlay.
 *
 * The stock runtime loads helper 0 from the TFT's 844-byte slot and calls it
 * while the graphical project is suspended. This loader:
 *   1. checks the expected display geometry and stock entry state;
 *   2. saves the UART and DMA state it is about to borrow;
 *   3. copies the CRC-checked program from external SPI 0x11000 to SRAM
 *      0x20000900 and verifies its CRC;
 *   4. calls pool_entry at 0x20000901 (Thumb);
 *   5. restores the stock touch cache, UART, DMA and interrupt state and lets
 *      the original state-4 continuation reload the project.
 *
 * terminal_receiver_meta.h is generated by tools/build_tft.py and contains
 * POOL_BYTES, POOL_CRC and POOL_ENTRY. It is deliberately not checked in: the
 * values must match the program just compiled.
 */
#include "terminal_api.h"
#include "terminal_receiver_meta.h"

uint32_t helper_entry(uint32_t width, uint32_t height, void *unused) {
  (void)unused;
  /* Only run from the known 480x320 stock entry, in the expected state, and
   * only when the UART/DMA are idle. Returning 0 leaves the stock path alone. */
  if (width != 480 || height != 320 ||
      *(volatile uint8_t *)0x20000101 != 2 || (R(D + 8) & 1) ||
      (R(U + 8) & 64))
    return 0;

  uint32_t cr1 = R(U), cr3 = R(U + 8), irq = R(0xe000e100) & (1u << 27);
  R(0xe000e180) = 1u << 27;      /* disable USART1 interrupt */
  R(0x20000130) = 0x0800115d;    /* stock continuation selector */

  /* Read POOL_BYTES from external SPI address 0x11000 (the TFT file's 4 KiB
   * preamble at offset 0x1000) into the suspended project's RAM pool. */
  ((void (*)(void *, uint32_t, uint32_t))0x08009371)(
      (void *)0x20000900, 0x11000, POOL_BYTES);
  ((void (*)(void))0x08002801)(); /* stock entry contract */

  uint32_t valid =
      ((uint32_t (*)(const void *, uint32_t))0x0800275d)(
          (void *)0x20000900, POOL_BYTES) == POOL_CRC;
  uint32_t held = 1;
  if (valid) held = ((uint32_t (*)(void))POOL_ENTRY)();

  /* The packet buffer is borrowed; leave it clear for the stock runtime. */
  ((void (*)(void *, uint32_t, uint32_t))0x0800c5c5)(
      (void *)0x200004f0, 1024, 0);

  /* The original state-4 continuation reloads project variables after this
   * helper returns. Calling it here would overwrite this helper's code. */
  ((void (*)(uint32_t))0x0800c7dd)(0x08003571);
  *(volatile uint8_t *)0x2000016a = held & 63;
  *(volatile uint16_t *)0x200002fa = 0;
  *(volatile uint16_t *)0x200002fc = 0;
  R(0x20000130) = held ? 0x0800115d : 0x0800b5d5;

  R(0xe000e180) = 1u << 27;
  R(U) = cr1;
  R(U + 8) = cr3;
  R(0xe000e280) = 1u << 27; /* clear pending USART1 */
  R(0xe000e100) = irq;      /* restore the saved enable state */
  return valid;
}
